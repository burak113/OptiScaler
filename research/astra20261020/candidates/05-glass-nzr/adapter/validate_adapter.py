"""Validate the job-05 source-only proposal without mutating production files.

Run on the recorded handoff checkout before applying the integration proposal.
This checks source scope, patch payload and applicability; it does not compile
HLSL, inspect generated bytecode, or execute a GPU.
"""

from pathlib import Path
import hashlib
import json
import subprocess
import time


HERE = Path(__file__).resolve().parent
REPO = HERE.parents[4]
BASE = "5d7839a930106cf8fe1ba8dbbc6750509e7f26a8"
TARGET = "OptiScaler/shaders/fsrd_preprocess/precompile/FSRDNrdFlatGlassUncertainty.hlsl"
PROTECTED = (
    "OptiScaler/shaders/fsrd_preprocess/FSRDNrdFlatAlbedoRecovery_Dx12.h",
    "OptiScaler/shaders/fsrd_preprocess/FSRDNrdBridgeRR_Dx12.cpp",
    "OptiScaler/shaders/fsrd_preprocess/FSRDNrdBridgeRR_Dx12.h",
    "OptiScaler/shaders/fsrd_preprocess/precompile/FSRDNrdFlatHybridApply.hlsl",
    "OptiScaler/shaders/fsrd_preprocess/precompile/FSRDFlatDetailBindings.hlsli",
)


def main():
    start = time.monotonic()
    source = (HERE / "GlassNzrCorrection.hlsl").read_bytes()
    patch = (HERE / "PRODUCTION.patch").read_bytes()
    expected = (
        f"diff --git a/{TARGET} b/{TARGET}\n"
        "new file mode 100644\n"
        "--- /dev/null\n"
        f"+++ b/{TARGET}\n"
        f"@@ -0,0 +1,{len(source.splitlines())} @@\n"
    ).encode() + b"".join(b"+" + line for line in source.splitlines(keepends=True))
    if patch != expected:
        raise AssertionError("Patch must add only the exact standalone HLSL; no existing-source edits")
    if b"\r" in source or not source.endswith(b"\n"):
        raise AssertionError("The new source and additive patch must retain their explicit LF endings")
    preserved = {}
    for relative in PROTECTED:
        frozen = subprocess.run(["git", "show", f"{BASE}:{relative}"], cwd=REPO,
                                check=True, capture_output=True).stdout
        actual = (REPO / relative).read_bytes()
        if actual != frozen:
            raise AssertionError(f"Protected original source changed: {relative}")
        preserved[relative] = hashlib.sha256(actual).hexdigest()
    run = subprocess.run(["git", "apply", "--check", str(HERE / "PRODUCTION.patch")],
                         cwd=REPO, text=True, capture_output=True)
    if run.returncode:
        raise AssertionError(f"Source-only proposal does not apply cleanly: {run.stderr}")
    print(json.dumps({
        "schema": "glass-nzr-adapter-source-validation-v1",
        "base_commit": BASE,
        "patch_applies": True,
        "patch_adds_only": TARGET,
        "source_sha256": hashlib.sha256(source).hexdigest(),
        "patch_sha256": hashlib.sha256(patch).hexdigest(),
        "protected_original_sha256": preserved,
        "elapsed_seconds": time.monotonic() - start,
        "hlsl_compiled": False,
        "gpu_executed": False,
        "native_graph_integrated": False,
    }, indent=2))


if __name__ == "__main__":
    main()
